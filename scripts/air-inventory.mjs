import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(root, "docs/air");
const previous = JSON.parse(
  await readFile(resolve(output, "surfaces.json"), "utf8").catch(() => '{"surfaces":[]}'),
);
const saved = new Map(previous.surfaces.map((surface) => [surface.path, surface]));
const scanRoot = await readdir(resolve(root, "src")).then(
  () => resolve(root, "src"),
  () => resolve(root, "apps/site/src"),
);
async function scan(directory, extensions = /\.(tsx|astro|css)$/) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const path = resolve(directory, entry.name);
      if (entry.isDirectory()) return scan(path, extensions);
      if (!extensions.test(entry.name) || /\.(test|spec)\./.test(entry.name)) return [];
      return [relative(root, path)];
    }),
  );
  return nested.flat();
}
const paths = [
  ...(await scan(scanRoot)),
  ...(await scan(resolve(root, "public"), /\.html$/)),
  ...(await scan(resolve(root, "artwork"), /\.html$/)),
  "index.html",
  "404.html",
].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const surfaces = paths.map(
  (path) =>
    saved.get(path) ?? {
      path,
      kind: path.includes("/templates/") ? "output-preservation" : "app-surface",
      sourceReviewed: false,
      airImplemented: false,
      validated: false,
      states: [],
      viewports: [],
      evidence: [],
      notes: "",
    },
);
const removed = previous.surfaces.filter((surface) => !paths.includes(surface.path));
if (removed.some((surface) => surface.validated)) {
  console.warn("Previously validated sources were removed; review their replacement coverage.");
}
const data = {
  schemaVersion: 1,
  contractVersion: JSON.parse(await readFile(resolve(output, "bundle.json"), "utf8")).version,
  note: "Presence in this inventory is not audit or validation. Preserve evidence when updating.",
  surfaces,
};
await mkdir(output, { recursive: true });
// Preserve the repository formatter's layout when the inventory is unchanged.
// CI checks semantic source drift; formatting alone must not rewrite evidence.
if (JSON.stringify(previous) !== JSON.stringify(data)) {
  await writeFile(resolve(output, "surfaces.json"), JSON.stringify(data, null, 2) + "\n");
}
const cells = [
  ["Source", "Kind", "Source audit", "Air implementation", "Validation"],
  ...surfaces.map((s) => [
    `\`${s.path}\``,
    s.kind,
    s.sourceReviewed ? "Done" : "Pending",
    s.airImplemented ? "Done" : "Pending",
    s.validated ? "Done" : "Pending",
  ]),
];
const widths = cells[0].map((_, index) => Math.max(...cells.map((row) => row[index].length)));
const row = (cells) => `| ${cells.map((cell, i) => cell.padEnd(widths[i])).join(" | ")} |`;
const rows = [
  row(cells[0]),
  row(widths.map((width) => "-".repeat(width))),
  ...cells.slice(1).map(row),
];
await writeFile(
  resolve(output, "surface-inventory.md"),
  `# Air surface inventory

${surfaces.length} source surfaces. Generated by \`node scripts/air-inventory.mjs\`.
\`surfaces.json\` is the progress/evidence record; generation preserves existing entries.
New sources default to pending. Runtime states and tool-registry entries must be
covered even when several are implemented by one file. Output templates require
preservation checks; their document design is not restyled.

Required applicable states: default, hover, focus, pressed/selected, disabled,
loading, empty, success, error, overflow and destructive confirmation/recovery.
Required layout classes: phone, landscape phone, tablet, laptop and desktop, in
light/dark, reduced motion and keyboard/touch modes as specified in DESIGN.md.

${rows.join("\n")}
`,
);
console.log(`Tracked ${surfaces.length} surfaces in ${relative(root, output)}.`);
